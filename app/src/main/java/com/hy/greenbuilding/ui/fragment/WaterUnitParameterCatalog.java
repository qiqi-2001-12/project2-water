    /** 每个分类页只承载一组可快速浏览的参数，避免单页过长。 */
    static List<Section> getPageSections(boolean statusPage) {
        List<Section> sections = getSections(statusPage);
        if (statusPage) {
            return sections;
        }

        List<Section> pages = new ArrayList<>();
        Section basic = sections.get(0);
        pages.add(new Section("基础运行", false, slice(basic.items, 0, 24)));
        pages.add(new Section("除霜温控", false, slice(basic.items, 24, basic.items.length)));
        pages.add(new Section("EEV 控制", false, sections.get(1).items));
        pages.add(new Section("机组风机", false, sections.get(2).items));
        pages.add(new Section("频率水泵", false, sections.get(3).items));
        pages.add(new Section("保护压力风机", false, sections.get(4).items));
        return pages;
    }

    private static String[] slice(String[] source, int from, int to) {
        return Arrays.copyOfRange(source, from, to);
    }

